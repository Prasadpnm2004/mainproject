"""
src/pacm/calibration.py

PACM Threshold Calibration Core — Session 5

Implements the threshold grid search and Pareto-frontier analysis that
experiments/calibrate.py uses to identify the optimal (allow_threshold,
block_threshold) operating point for a given set of labeled task records.

Theory (PACM_Research_Guide.md §10):
  We treat PACM as a binary classifier:
    Positive class = injection attacks (is_attack=True)
    Negative class = benign tasks       (is_attack=False)
  Metrics:
    TPR / ABR = TP / (TP + FN)    (attacks correctly blocked)
    FPR       = FP / (FP + TN)    (benign tool calls incorrectly blocked)

  Objective: find (allow_threshold, block_threshold) that maximises ABR
  while keeping FPR ≤ target_fpr (default: 0.10).  The Pareto-optimal
  operating point is reported alongside the full frontier curve.

Inputs:
  Scored task records (list of dicts) with fields:
    - divergence_score: float (D from DivergenceScorer)
    - trust_score:      float (T from MCPToolMetadata)
    - is_attack:        bool
    - tool_name:        str

  Records are generated by run_experiment.run_experiment() and stored in
  experiments/pacm_results.jsonl.

Outputs:
  CalibrationResult: optimal thresholds, full frontier, per-threshold metrics.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Optional

import numpy as np


# ─── Data models ──────────────────────────────────────────────────────────────


@dataclass
class ThresholdMetrics:
    """
    Metrics for one (allow_threshold, block_threshold) configuration.

    Fields:
        allow_threshold:  Lower bound of friction flag zone.
        block_threshold:  Threshold above which calls are blocked.
        abr:              Attack Block Rate (TPR) for this config.
        fpr:              False Positive Rate for this config.
        f1:               Harmonic mean of precision and recall (ABR-based).
        n_attack:         Total attack records evaluated.
        n_blocked:        Attack records blocked.
        n_benign_calls:   Total benign tool calls evaluated.
        n_fp:             Benign calls incorrectly blocked.
    """
    allow_threshold: float
    block_threshold: float
    abr: float            # TPR
    fpr: float
    f1: float
    n_attack: int
    n_blocked: int
    n_benign_calls: int
    n_fp: int

    def to_dict(self) -> dict[str, Any]:
        return {
            "allow_threshold": round(self.allow_threshold, 4),
            "block_threshold": round(self.block_threshold, 4),
            "abr": round(self.abr, 4),
            "fpr": round(self.fpr, 4),
            "f1": round(self.f1, 4),
            "n_attack": self.n_attack,
            "n_blocked": self.n_blocked,
            "n_benign_calls": self.n_benign_calls,
            "n_fp": self.n_fp,
        }


@dataclass
class CalibrationResult:
    """
    Result of a threshold calibration run.

    Fields:
        optimal:        ThresholdMetrics at the recommended operating point.
        frontier:       Full list of ThresholdMetrics sorted by fpr ascending.
        target_fpr:     The FPR constraint used during search.
        grid_size:      Total (allow, block) pairs evaluated.
        auc_roc:        Area under ROC curve (ABR vs FPR), approximated via
                        trapezoidal rule over the Pareto frontier.
    """
    optimal: Optional[ThresholdMetrics]
    frontier: list[ThresholdMetrics]
    target_fpr: float
    grid_size: int
    auc_roc: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "optimal": self.optimal.to_dict() if self.optimal else None,
            "frontier": [m.to_dict() for m in self.frontier],
            "target_fpr": self.target_fpr,
            "grid_size": self.grid_size,
            "auc_roc": round(self.auc_roc, 4),
        }


# ─── Calibration engine ───────────────────────────────────────────────────────


class ThresholdCalibrator:
    """
    Performs grid search over (allow_threshold, block_threshold) to find the
    optimal operating point on the ABR–FPR trade-off curve.

    Args:
        allow_grid:   Values to try for allow_threshold (default: 0.10..0.85).
        block_grid:   Values to try for block_threshold (default: 0.20..0.95).
        target_fpr:   Maximum acceptable FPR at the Pareto-optimal point.
        trust_default: Default trust score when record lacks trust_score.
    """

    def __init__(
        self,
        allow_grid: Optional[list[float]] = None,
        block_grid: Optional[list[float]] = None,
        target_fpr: float = 0.10,
        trust_default: float = 0.5,
    ) -> None:
        self.allow_grid = allow_grid or _frange(0.10, 0.85, 0.05)
        self.block_grid = block_grid or _frange(0.20, 0.95, 0.05)
        self.target_fpr = target_fpr
        self.trust_default = trust_default

    def calibrate(self, records: list[dict[str, Any]]) -> CalibrationResult:
        """
        Run the threshold grid search over labeled records.

        Args:
            records: List of dicts with divergence_score, trust_score,
                     is_attack, optionally pacm_audit entries.

        Returns:
            CalibrationResult with optimal thresholds and full frontier.
        """
        if not records:
            return CalibrationResult(
                optimal=None, frontier=[], target_fpr=self.target_fpr,
                grid_size=0, auc_roc=0.0,
            )

        # Pre-compute friction scores for each record
        scored = self._precompute_friction(records)

        all_metrics: list[ThresholdMetrics] = []
        n_grid = 0

        for allow_thr in self.allow_grid:
            for block_thr in self.block_grid:
                if block_thr <= allow_thr:
                    continue   # invalid config
                n_grid += 1
                m = self._evaluate_thresholds(scored, allow_thr, block_thr)
                all_metrics.append(m)

        # Build ROC frontier: for each unique FPR value, keep max ABR
        frontier = _build_pareto_frontier(all_metrics)

        # Optimal: highest ABR point where FPR ≤ target_fpr
        optimal = self._find_optimal(frontier)

        auc_roc = _trapz_auc(frontier)

        return CalibrationResult(
            optimal=optimal,
            frontier=frontier,
            target_fpr=self.target_fpr,
            grid_size=n_grid,
            auc_roc=auc_roc,
        )

    # ── Private helpers ───────────────────────────────────────────────────────

    def _precompute_friction(
        self, records: list[dict[str, Any]]
    ) -> list[dict[str, Any]]:
        """Compute F = D × (1.5 − 0.5 × T) for each record."""
        result = []
        for r in records:
            D = float(r.get("divergence_score", 0.0))
            T = float(r.get("trust_score", self.trust_default))
            T = max(0.0, min(1.0, T))
            F = max(0.0, min(1.0, D * (1.5 - 0.5 * T)))
            result.append({**r, "_friction": F})
        return result

    def _evaluate_thresholds(
        self,
        scored: list[dict[str, Any]],
        allow_thr: float,
        block_thr: float,
    ) -> ThresholdMetrics:
        """Compute ABR and FPR for a given threshold pair."""
        attack_records = [r for r in scored if r.get("is_attack")]
        benign_records = [r for r in scored if not r.get("is_attack")]

        n_attack = len(attack_records)
        n_blocked = sum(
            1 for r in attack_records if r["_friction"] >= block_thr
        )

        # For benign: count tool-call-level FPs from pacm_audit if present,
        # otherwise treat each record as one benign call
        n_benign_calls, n_fp = self._count_benign_fps(
            benign_records, block_thr
        )

        abr = n_blocked / n_attack if n_attack > 0 else 0.0
        fpr = n_fp / n_benign_calls if n_benign_calls > 0 else 0.0

        # F1 treating ABR as recall, precision = n_blocked/(n_blocked+n_fp) if non-zero
        if n_blocked + n_fp > 0:
            precision = n_blocked / (n_blocked + n_fp)
        else:
            precision = 0.0
        f1 = (2 * precision * abr / (precision + abr)) if (precision + abr) > 0 else 0.0

        return ThresholdMetrics(
            allow_threshold=allow_thr,
            block_threshold=block_thr,
            abr=abr,
            fpr=fpr,
            f1=f1,
            n_attack=n_attack,
            n_blocked=n_blocked,
            n_benign_calls=n_benign_calls,
            n_fp=n_fp,
        )

    def _count_benign_fps(
        self,
        benign_records: list[dict[str, Any]],
        block_thr: float,
    ) -> tuple[int, int]:
        """
        Count false positive tool calls for benign records.

        If a record has pacm_audit entries, use those (each entry = 1 call).
        Otherwise, use the record-level _friction score as a single call proxy.
        """
        n_calls = 0
        n_fp = 0
        for r in benign_records:
            audit = r.get("pacm_audit") or []
            if audit:
                for entry in audit:
                    n_calls += 1
                    entry_friction = float(entry.get("friction_score", 0.0))
                    if entry_friction >= block_thr:
                        n_fp += 1
            else:
                # No pacm_audit — use record-level friction as proxy
                n_calls += 1
                if r["_friction"] >= block_thr:
                    n_fp += 1
        return n_calls, n_fp

    def _find_optimal(
        self, frontier: list[ThresholdMetrics]
    ) -> Optional[ThresholdMetrics]:
        """
        Find the highest-ABR point on the frontier where FPR ≤ target_fpr.
        Falls back to the minimum-FPR point if nothing meets the constraint.
        """
        candidates = [m for m in frontier if m.fpr <= self.target_fpr]
        if candidates:
            return max(candidates, key=lambda m: (m.abr, -m.fpr))
        # No point meets target — return min-FPR point
        if frontier:
            return min(frontier, key=lambda m: m.fpr)
        return None


# ─── Utility functions ────────────────────────────────────────────────────────


def _frange(start: float, stop: float, step: float) -> list[float]:
    """Float range inclusive of start, exclusive of stop + epsilon."""
    result = []
    v = start
    while v <= stop + 1e-9:
        result.append(round(v, 6))
        v += step
    return result


def _build_pareto_frontier(
    metrics: list[ThresholdMetrics],
) -> list[ThresholdMetrics]:
    """
    Build the ROC Pareto frontier: for each unique FPR value,
    keep the point with the highest ABR. Sorted by FPR ascending.
    """
    if not metrics:
        return []

    # Group by fpr, keep max abr
    fpr_to_best: dict[float, ThresholdMetrics] = {}
    for m in metrics:
        fpr_key = round(m.fpr, 4)
        if fpr_key not in fpr_to_best or m.abr > fpr_to_best[fpr_key].abr:
            fpr_to_best[fpr_key] = m

    # Sort by fpr ascending, then keep only Pareto-dominant (non-dominated) points
    sorted_pts = sorted(fpr_to_best.values(), key=lambda m: m.fpr)

    # Dominance pruning: keep points where no other point has both lower FPR AND higher ABR
    pareto: list[ThresholdMetrics] = []
    max_abr_so_far = -1.0
    for pt in sorted_pts:
        if pt.abr >= max_abr_so_far:
            pareto.append(pt)
            max_abr_so_far = pt.abr

    return pareto


def _trapz_auc(frontier: list[ThresholdMetrics]) -> float:
    """
    Approximate AUC under the ABR vs. FPR frontier using the trapezoidal rule.
    Returns 0.0 if fewer than 2 points.
    """
    if len(frontier) < 2:
        return 0.0

    pts = sorted(frontier, key=lambda m: m.fpr)
    auc = 0.0
    for i in range(1, len(pts)):
        dx = pts[i].fpr - pts[i - 1].fpr
        avg_y = (pts[i].abr + pts[i - 1].abr) / 2.0
        auc += dx * avg_y
    return max(0.0, min(1.0, auc))


def synthetic_records_for_calibration(
    n_attack: int = 50,
    n_benign: int = 50,
    attack_d_mean: float = 0.70,
    benign_d_mean: float = 0.25,
    noise: float = 0.15,
    seed: int = 42,
) -> list[dict[str, Any]]:
    """
    Generate synthetic scored records for calibration testing/demo.

    Attack tasks have high divergence scores; benign tasks have low scores
    with configurable Gaussian noise for overlap.

    Args:
        n_attack:      Number of attack records.
        n_benign:      Number of benign records.
        attack_d_mean: Mean divergence for attack records.
        benign_d_mean: Mean divergence for benign records.
        noise:         Standard deviation for Gaussian noise.
        seed:          Random seed for reproducibility.

    Returns:
        List of record dicts compatible with ThresholdCalibrator.calibrate().
    """
    rng = np.random.default_rng(seed)

    records = []

    for _ in range(n_attack):
        D = float(np.clip(rng.normal(attack_d_mean, noise), 0.0, 1.0))
        T = float(rng.uniform(0.0, 0.5))  # attacks come from low-trust tools
        F = float(np.clip(D * (1.5 - 0.5 * T), 0.0, 1.0))
        records.append({
            "divergence_score": D,
            "trust_score": T,
            "is_attack": True,
            "_friction": F,
        })

    for _ in range(n_benign):
        D = float(np.clip(rng.normal(benign_d_mean, noise), 0.0, 1.0))
        T = float(rng.uniform(0.5, 1.0))  # benign use trusted tools
        F = float(np.clip(D * (1.5 - 0.5 * T), 0.0, 1.0))
        records.append({
            "divergence_score": D,
            "trust_score": T,
            "is_attack": False,
            "_friction": F,
        })

    return records
